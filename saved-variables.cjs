const reserved = new Set("and break do else elseif end false for function goto if in local nil not or repeat return then true until while".split(" "));
const generatedHeader = "---@meta\n-- Generated by Zilvereyes WoW TOC from SavedVariables. Editor only.\n";

function generateSavedVariables(source, text, sdk) {
    const { metadata, diagnostics } = sdk.parseToc(text, source);
    const errors = diagnostics.filter(issue => issue.severity === "error");
    if (errors.length) {
        throw new Error(errors.map(issue => issue.message).join("; "));
    }

    const invalid = metadata.savedVariableDeclarations.find(item => !item.validIdentifier);
    if (invalid) throw new Error("Invalid Lua global in SavedVariables: " + invalid.name);
    const declarations = sdk.toGlobalDeclarations([metadata]);
    const names = new Set();
    for (const { name, kind, activationState } of declarations) {
        if (kind !== "saved-variable" || activationState !== "unconditional") continue;
        if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) || reserved.has(name)) {
            throw new Error("Invalid Lua global in SavedVariables: " + name);
        }
        names.add(name);
    }

    return {
        names: [...names],
        conditional: declarations.filter(item => item.activationState === "conditional").length,
        text: generatedHeader + [...names].map(name => "\n---@type any\n" + name + " = nil\n").join(""),
    };
}

module.exports = { generateSavedVariables, generatedHeader };
